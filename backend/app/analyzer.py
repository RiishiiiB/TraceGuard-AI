"""CSV parsing/validation and the end-to-end analysis pipeline."""
import io
import ipaddress
import re
import uuid
from datetime import datetime, timezone

import pandas as pd

from . import scoring
from .config import CONFIG, DetectionConfig
from .correlator import correlate
from .detector import detect
from .schemas import AnalysisResult, DatasetSummary, Event

REQUIRED_COLUMNS = ["timestamp", "username", "source_ip", "event_type", "status"]
EVENT_TYPES = {"login", "logout", "password_reset"}
STATUS_ALIASES = {"success": "success", "succeeded": "success", "ok": "success",
                  "failure": "failure", "failed": "failure", "fail": "failure"}
TZ_SUFFIX = re.compile(r"(?:[zZ]|[+-]\d{2}:?\d{2})$")

DEMO_NOTICE = ("SYNTHETIC DEMONSTRATION DATA - generated by TraceGuard AI for demonstration. "
               "Nothing in this dataset represents a real attack or a real person.")
UPLOAD_NOTICE = ("Analysis of an uploaded file. Findings are heuristic indicators from authentication logs only; "
                 "no IP geolocation, threat-intelligence or attribution is performed.")


class LogValidationError(Exception):
    def __init__(self, message: str, details: list[str] | None = None, status: int = 422):
        super().__init__(message)
        self.message, self.details, self.status = message, details or [], status


def _valid_ip(value: str) -> bool:
    try:
        ipaddress.ip_address(value)
        return True
    except ValueError:
        return False


def parse_csv(data: bytes, cfg: DetectionConfig = CONFIG):
    """Return (events, stats). Raises LogValidationError for unusable files."""
    if not data or not data.strip():
        raise LogValidationError("The uploaded file is empty.", status=400)
    if len(data) > cfg.max_upload_bytes:
        raise LogValidationError(f"File is larger than the {cfg.max_upload_bytes // (1024 * 1024)} MB limit.", status=413)
    if b"\x00" in data:
        raise LogValidationError("File does not look like a text CSV (contains binary data).", status=400)
    try:
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError:
        raise LogValidationError("File is not valid UTF-8 text. Export the log as a UTF-8 CSV.", status=400)

    try:
        df = pd.read_csv(io.StringIO(text), dtype=str, keep_default_na=False, on_bad_lines="error",
                         skipinitialspace=True)
    except (pd.errors.ParserError, pd.errors.EmptyDataError) as exc:
        raise LogValidationError("The file is not a well-formed CSV.", [str(exc).splitlines()[0]])

    df.columns = [str(c).strip().lower() for c in df.columns]
    missing = [c for c in REQUIRED_COLUMNS if c not in df.columns]
    if missing:
        raise LogValidationError(
            f"Missing required column(s): {', '.join(missing)}.",
            [f"Required columns: {', '.join(REQUIRED_COLUMNS)}", f"Columns found: {', '.join(df.columns) or '(none)'}"])
    if len(df) > cfg.max_rows:
        raise LogValidationError(f"File has {len(df)} rows; the demo limit is {cfg.max_rows}.", status=413)

    for col in REQUIRED_COLUMNS:
        df[col] = df[col].astype(str).str.strip()
    ts = pd.to_datetime(df["timestamp"], utc=True, errors="coerce", format="mixed")
    naive = int((~df["timestamp"].str.contains(TZ_SUFFIX) & ts.notna()).sum())
    etype = df["event_type"].str.lower()
    status = df["status"].str.lower().map(STATUS_ALIASES)

    reasons = {
        "invalid or missing timestamp": ts.isna(),
        "missing username": df["username"] == "",
        "missing or invalid source_ip": ~df["source_ip"].map(_valid_ip),
        "unsupported event_type (expected login, logout, password_reset)": ~etype.isin(EVENT_TYPES),
        "invalid status (expected success or failure)": status.isna(),
    }
    bad = pd.Series(False, index=df.index, dtype=bool)
    row_errors: list[str] = []
    for label, mask in reasons.items():
        mask = mask.astype(bool)
        new = mask & ~bad
        for idx in df.index[new][: max(0, 8 - len(row_errors))]:
            row_errors.append(f"row {idx + 2}: {label}")
        bad |= mask
    skipped = int(bad.sum())
    if len(df) and skipped == len(df):
        raise LogValidationError("No valid rows found in the file.", row_errors)

    warnings = []
    if naive:
        warnings.append(f"{naive} timestamp(s) had no timezone and were interpreted as UTC.")
    if skipped:
        warnings.append(f"{skipped} malformed row(s) were skipped.")

    events, seen, dup = [], set(), 0
    for idx in df.index[~bad]:
        key = (ts[idx], df.at[idx, "username"].lower(), df.at[idx, "source_ip"], etype[idx], status[idx])
        if key in seen:
            dup += 1
            continue
        seen.add(key)
        events.append(Event(
            id="", row=int(idx) + 2, timestamp=ts[idx].to_pydatetime(), username=key[1],
            source_ip=key[2], event_type=key[3], status=key[4]))
    if dup:
        warnings.append(f"{dup} exact duplicate event(s) were removed.")
    return events, {"rows_received": len(df), "rows_skipped": skipped, "duplicates_removed": dup,
                    "warnings": warnings, "row_errors": row_errors}


def analyze_events(events: list[Event], stats: dict, source_name: str, is_demo: bool,
                   cfg: DetectionConfig = CONFIG) -> AnalysisResult:
    events = sorted(events, key=lambda e: (e.timestamp, e.row))
    for n, e in enumerate(events, start=1):
        e.id = f"E{n:05d}"
    by_id = {e.id: e for e in events}

    findings = detect(events, cfg)
    findings.sort(key=lambda f: (f.first_seen, f.rule_id, f.source_ips))
    for n, f in enumerate(findings, start=1):
        f.id = f"F-{n:03d}"
        for eid in f.event_ids:
            by_id[eid].finding_ids.append(f.id)
            by_id[eid].suspicious = True
    incidents = correlate(findings, by_id, cfg)

    sev = ["LOW", "MEDIUM", "HIGH", "CRITICAL"]
    summary = DatasetSummary(
        total_events=len(events),
        suspicious_events=sum(1 for e in events if e.suspicious),
        findings_count=len(findings),
        incidents_count=len(incidents),
        high_critical_incidents=sum(1 for i in incidents if i.severity in ("HIGH", "CRITICAL")),
        incidents_by_severity={s: sum(1 for i in incidents if i.severity == s) for s in sev},
        findings_by_severity={s: sum(1 for f in findings if f.severity == s) for s in sev},
        unique_users=len({e.username for e in events}),
        unique_ips=len({e.source_ip for e in events}),
        first_event=events[0].timestamp if events else None,
        last_event=events[-1].timestamp if events else None,
        rows_received=stats.get("rows_received", len(events)),
        rows_skipped=stats.get("rows_skipped", 0),
        duplicates_removed=stats.get("duplicates_removed", 0),
        warnings=stats.get("warnings", []) + ([] if events else ["The file contains no events."]),
        row_errors=stats.get("row_errors", []),
    )
    return AnalysisResult(
        analysis_id=uuid.uuid4().hex[:12], created_at=datetime.now(timezone.utc), source_name=source_name,
        is_demo=is_demo, data_notice=DEMO_NOTICE if is_demo else UPLOAD_NOTICE, summary=summary,
        events=events, findings=findings, incidents=incidents, config=cfg.as_dict(),
    )


def analyze_csv(data: bytes, source_name: str, is_demo: bool = False,
                cfg: DetectionConfig = CONFIG) -> AnalysisResult:
    events, stats = parse_csv(data, cfg)
    return analyze_events(events, stats, source_name, is_demo, cfg)


def build_report(result: AnalysisResult) -> dict:
    """JSON investigation report derived only from the analysis result."""
    from .detector import rule_catalog

    by_id = {e.id: e for e in result.events}
    cfg = DetectionConfig(**result.config)
    findings = []
    for f in result.findings:
        d = f.model_dump(mode="json")
        d["source_events"] = [by_id[i].model_dump(mode="json") for i in f.event_ids]
        findings.append(d)
    return {
        "report_type": "TraceGuard AI investigation report",
        "analysis_id": result.analysis_id,
        "analysis_timestamp": result.created_at.isoformat(),
        "data_source": {"name": result.source_name, "synthetic_demo_data": result.is_demo, "notice": result.data_notice},
        "dataset_summary": result.summary.model_dump(mode="json"),
        "detection_rules": [r.model_dump(mode="json") for r in rule_catalog(cfg)],
        "detection_config": result.config,
        "scoring_model": scoring.SCORING_MODEL,
        "incidents": [i.model_dump(mode="json") for i in result.incidents],
        "findings": findings,
        "disclaimer": "Risk scores are transparent heuristics, not calibrated probabilities of compromise. "
                      "Findings are indicators for human review and do not prove an attack.",
    }
