import { Download, FlaskConical, Upload } from 'lucide-react'
import { api } from '../services/api'
import { useAnalysis } from '../services/AnalysisContext'
import { useUploadPicker } from './Shell'

const SCHEMA = [
  ['timestamp', 'ISO 8601, e.g. 2025-03-10T14:02:10Z (no timezone = UTC)'],
  ['username', 'Account name, e.g. admin'],
  ['source_ip', 'IPv4 or IPv6 address'],
  ['event_type', 'login, logout or password_reset'],
  ['status', 'success or failure'],
]

export default function EmptyState() {
  const { loadDemo, loading } = useAnalysis()
  const pick = useUploadPicker()
  return (
    <div className="empty-state">
      <div className="label" style={{ marginBottom: 10 }}>No analysis loaded</div>
      <h2>Load an authentication log to start an investigation.</h2>
      <p className="muted" style={{ maxWidth: '62ch' }}>
        TraceGuard AI applies deterministic detection rules to login events, correlates findings into
        incidents and shows the exact evidence behind every score. Nothing needs signing in or configuring.
      </p>
      <div className="actions">
        <button className="btn primary" onClick={loadDemo} disabled={loading}><FlaskConical size={15} /> Load demo data</button>
        <button className="btn" onClick={pick} disabled={loading}><Upload size={15} /> Upload CSV</button>
        <a className="btn ghost" href={api.sampleCsvUrl}><Download size={15} /> Sample CSV</a>
      </div>
      <div className="label" style={{ marginBottom: 8 }}>Expected CSV columns</div>
      <table className="schema">
        <thead><tr><th>Column</th><th>Format</th></tr></thead>
        <tbody>{SCHEMA.map(([c, d]) => <tr key={c}><td className="mono">{c}</td><td>{d}</td></tr>)}</tbody>
      </table>
      <p className="muted" style={{ marginTop: 12, fontSize: 12 }}>
        Demo data is synthetic and generated by this application. Uploaded files are analysed in memory and not stored on disk.
      </p>
    </div>
  )
}
